CREATE TABLE IF NOT EXISTS public.groups (
    group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name TEXT NOT NULL,
    course TEXT NOT NULL,
    specialty TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    owner_id BIGINT REFERENCES public.users(user_id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'Full')),
    max_members INTEGER NOT NULL DEFAULT 4 CHECK (max_members BETWEEN 2 AND 4),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.group_members (
    group_id BIGINT NOT NULL REFERENCES public.groups(group_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, user_id),
    CONSTRAINT group_members_user_id_unique UNIQUE (user_id)
);

INSERT INTO public.group_members (group_id, user_id)
SELECT group_id, owner_id
FROM public.groups
WHERE owner_id IS NOT NULL
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS public.group_join_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES public.groups(group_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT group_join_requests_group_user_unique UNIQUE (group_id, user_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS group_join_requests_one_pending_per_user
    ON public.group_join_requests(user_id) WHERE status = 'Pending';
CREATE INDEX IF NOT EXISTS groups_created_at_idx ON public.groups(created_at DESC);
CREATE INDEX IF NOT EXISTS group_members_group_id_idx ON public.group_members(group_id);
CREATE INDEX IF NOT EXISTS group_join_requests_group_status_idx ON public.group_join_requests(group_id, status);

