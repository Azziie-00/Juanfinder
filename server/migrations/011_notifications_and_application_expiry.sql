CREATE OR REPLACE FUNCTION public.guard_adviser_application_deadline()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.expires_at := NEW.created_at + INTERVAL '24 hours';
    ELSE
        IF NEW.created_at IS DISTINCT FROM OLD.created_at OR NEW.expires_at IS DISTINCT FROM OLD.expires_at THEN
            RAISE EXCEPTION 'Application submission and expiration timestamps cannot be changed.';
        END IF;
        IF OLD.status <> 'Pending' AND NEW.status IS DISTINCT FROM OLD.status THEN
            RAISE EXCEPTION 'This adviser application has already been processed.';
        END IF;
        IF OLD.status = 'Pending' AND NEW.status IN ('Accepted','Rejected') AND OLD.expires_at <= clock_timestamp() THEN
            NEW.status := 'Expired';
        END IF;
        IF NEW.status = 'Expired' AND OLD.status = 'Pending' THEN
            IF OLD.expires_at > clock_timestamp() THEN RAISE EXCEPTION 'An application cannot expire before its deadline.'; END IF;
            NEW.responded_at := OLD.expires_at;
        ELSIF NEW.status IN ('Accepted','Rejected') AND OLD.status = 'Pending' THEN
            NEW.responded_at := clock_timestamp();
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS guard_adviser_application_deadline ON public.group_adviser_applications;
CREATE TRIGGER guard_adviser_application_deadline BEFORE INSERT OR UPDATE ON public.group_adviser_applications
    FOR EACH ROW EXECUTE FUNCTION public.guard_adviser_application_deadline();

CREATE OR REPLACE FUNCTION public.notify_adviser_application_event()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
DECLARE group_name TEXT; adviser_name TEXT;
BEGIN
    IF OLD.status <> 'Pending' OR NEW.status NOT IN ('Accepted','Expired') THEN RETURN NEW; END IF;
    SELECT g.group_name, u.name INTO group_name, adviser_name FROM public.groups g
        JOIN public.users u ON u.user_id = NEW.adviser_id WHERE g.group_id = NEW.group_id;
    INSERT INTO public.notifications(recipient_id, notification_type, title, message, application_id, group_id, event_key)
    VALUES (NEW.applicant_id,
        CASE NEW.status WHEN 'Accepted' THEN 'adviser_application_accepted' ELSE 'adviser_application_expired' END,
        CASE NEW.status WHEN 'Accepted' THEN 'Adviser application accepted' ELSE 'Adviser application expired' END,
        CASE NEW.status WHEN 'Accepted' THEN format('%s accepted your application for %s.', adviser_name, group_name)
            ELSE format('Your application for %s to %s expired after 24 hours. You can apply again.', group_name, adviser_name) END,
        NEW.application_id, NEW.group_id, 'adviser-application:' || NEW.application_id || ':' || NEW.status)
    ON CONFLICT (event_key) DO NOTHING;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS notify_adviser_application_event ON public.group_adviser_applications;
CREATE TRIGGER notify_adviser_application_event AFTER UPDATE OF status ON public.group_adviser_applications
    FOR EACH ROW EXECUTE FUNCTION public.notify_adviser_application_event();

CREATE OR REPLACE FUNCTION public.expire_group_adviser_applications(p_group_id BIGINT DEFAULT NULL)
RETURNS INTEGER LANGUAGE plpgsql SET search_path = public AS $$
DECLARE target_id BIGINT; affected INTEGER := 0; changed INTEGER;
BEGIN
    IF p_group_id IS NOT NULL THEN
        -- Specific reads/submissions wait for an in-flight acceptance to finish.
        PERFORM group_id FROM public.groups WHERE group_id = p_group_id FOR UPDATE;
        UPDATE public.group_adviser_applications SET status = 'Expired', responded_at = expires_at
        WHERE group_id = p_group_id AND status = 'Pending' AND expires_at <= clock_timestamp();
        GET DIAGNOSTICS affected = ROW_COUNT;
    ELSE
        -- Scheduled work skips busy groups; every acceptance still checks its own deadline.
        FOR target_id IN SELECT g.group_id FROM public.groups g
            WHERE EXISTS (SELECT 1 FROM public.group_adviser_applications a WHERE a.group_id = g.group_id
                AND a.status = 'Pending' AND a.expires_at <= clock_timestamp())
            ORDER BY g.group_id FOR UPDATE OF g SKIP LOCKED
        LOOP
            UPDATE public.group_adviser_applications SET status = 'Expired', responded_at = expires_at
            WHERE group_id = target_id AND status = 'Pending' AND expires_at <= clock_timestamp();
            GET DIAGNOSTICS changed = ROW_COUNT;
            affected := affected + changed;
        END LOOP;
    END IF;
    RETURN affected;
END;
$$;

