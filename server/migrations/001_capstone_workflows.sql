CREATE OR REPLACE FUNCTION public.issue_temporary_account(
    p_user_id BIGINT,
    p_password_hash TEXT,
    p_expires_at TIMESTAMPTZ
) RETURNS VOID
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    target_user public.users;
BEGIN
    SELECT * INTO target_user FROM public.users WHERE user_id = p_user_id FOR UPDATE;
    IF NOT FOUND OR target_user.role NOT IN ('student', 'adviser') THEN
        RAISE EXCEPTION 'Only student or adviser accounts may receive temporary access.';
    END IF;
    UPDATE public.temporary_accounts SET status = 'Revoked'
    WHERE user_id = p_user_id AND status = 'Pending';
    INSERT INTO public.temporary_accounts (user_id, email, role, password_hash, expires_at)
    VALUES (p_user_id, target_user.username, target_user.role, p_password_hash, p_expires_at);
    DELETE FROM public.auth_sessions WHERE user_id = p_user_id;
    UPDATE public.users SET password_hash = p_password_hash, password_change_required = TRUE,
        expires_at = p_expires_at, is_active = TRUE
    WHERE user_id = p_user_id;
END;
$$;
