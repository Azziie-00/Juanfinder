CREATE OR REPLACE FUNCTION public.update_owned_group(
    p_group_id BIGINT,
    p_owner_id BIGINT,
    p_name TEXT,
    p_description TEXT,
    p_specialty TEXT,
    p_max_members INTEGER
) RETURNS VOID
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    target_group public.groups;
    member_count INTEGER;
BEGIN
    SELECT * INTO target_group FROM public.groups WHERE group_id = p_group_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Group not found.'; END IF;
    IF target_group.owner_id <> p_owner_id THEN RAISE EXCEPTION 'Only the group owner can manage members.'; END IF;
    IF target_group.finalized_at IS NOT NULL THEN RAISE EXCEPTION 'This group is finalized.'; END IF;
    IF p_max_members < 2 OR p_max_members > 4 OR NOT p_name ~ '\S' THEN
        RAISE EXCEPTION 'Group details are invalid.';
    END IF;
    SELECT COUNT(*) INTO member_count FROM public.group_members WHERE group_id = p_group_id;
    IF p_max_members < member_count THEN RAISE EXCEPTION 'Maximum size cannot be below the current member count.'; END IF;
    UPDATE public.groups
    SET group_name = trim(p_name), description = trim(p_description),
        specialty = trim(p_specialty), max_members = p_max_members,
        status = CASE WHEN member_count >= p_max_members THEN 'Full' ELSE 'Open' END
    WHERE group_id = p_group_id;
    IF member_count >= p_max_members THEN
        UPDATE public.group_join_requests SET status = 'Expired'
        WHERE group_id = p_group_id AND status = 'Pending';
    END IF;
END;
$$;

