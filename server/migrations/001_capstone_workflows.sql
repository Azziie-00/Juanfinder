CREATE OR REPLACE FUNCTION public.create_group_with_owner(
    p_name TEXT,
    p_course TEXT,
    p_specialty TEXT,
    p_description TEXT,
    p_owner_id BIGINT,
    p_max_members INTEGER
) RETURNS public.groups
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    created_group public.groups;
BEGIN
    IF p_max_members < 2 OR p_max_members > 4 THEN
