CREATE OR REPLACE FUNCTION public.admin_change_finalized_group_member(
    p_group_id BIGINT,
    p_student_id BIGINT,
    p_admin_id BIGINT,
    p_action TEXT
) RETURNS VOID
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    target_group public.groups;
    member_count INTEGER;
BEGIN
    IF p_action NOT IN ('add', 'remove') THEN RAISE EXCEPTION 'Membership action is invalid.'; END IF;
    IF NOT EXISTS (SELECT 1 FROM public.users WHERE user_id = p_admin_id AND role IN ('admin', 'superadmin') AND is_active) THEN
        RAISE EXCEPTION 'Admin access is required.';
    END IF;
    SELECT * INTO target_group FROM public.groups WHERE group_id = p_group_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Group not found.'; END IF;
    IF target_group.finalized_at IS NULL THEN RAISE EXCEPTION 'Administrative override is only for finalized groups.'; END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.users
        WHERE user_id = p_student_id AND role = 'student' AND is_active
          AND (expires_at IS NULL OR expires_at > NOW())
    ) THEN
        RAISE EXCEPTION 'Only active student accounts may be group members.';
    END IF;
    IF p_action = 'add' AND EXISTS (SELECT 1 FROM public.group_members WHERE user_id = p_student_id) THEN
        RAISE EXCEPTION 'Student already belongs to a group.';
    END IF;

    SELECT COUNT(*) INTO member_count FROM public.group_members WHERE group_id = p_group_id;
    IF p_action = 'add' THEN
        IF member_count >= target_group.max_members THEN RAISE EXCEPTION 'This group is full.'; END IF;
        INSERT INTO public.group_members (group_id, user_id) VALUES (p_group_id, p_student_id);
    ELSE
        IF p_student_id = target_group.owner_id THEN RAISE EXCEPTION 'The group leader cannot be removed.'; END IF;
        DELETE FROM public.group_members WHERE group_id = p_group_id AND user_id = p_student_id;
        IF NOT FOUND THEN RAISE EXCEPTION 'Student is not in this group.'; END IF;
    END IF;

    INSERT INTO public.group_membership_audit (group_id, user_id, admin_id, action)
    VALUES (p_group_id, p_student_id, p_admin_id, p_action);
    SELECT COUNT(*) INTO member_count FROM public.group_members WHERE group_id = p_group_id;
    UPDATE public.groups SET status = CASE WHEN member_count >= max_members THEN 'Full' ELSE 'Open' END
    WHERE group_id = p_group_id;
END;
$$;

