CREATE OR REPLACE FUNCTION public.request_to_join_group(
    p_group_id BIGINT,
    p_user_id BIGINT,
    p_allow_superadmin BOOLEAN DEFAULT FALSE
) RETURNS VOID
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    target_group public.groups;
    member_count INTEGER;
BEGIN
    UPDATE public.group_join_requests
    SET status = 'Expired'
    WHERE user_id = p_user_id AND status = 'Pending' AND expires_at <= NOW();

    IF NOT EXISTS (
        SELECT 1 FROM public.users
        WHERE user_id = p_user_id
          AND (role = 'student' OR (p_allow_superadmin AND role = 'superadmin'))
          AND is_active AND (expires_at IS NULL OR expires_at > NOW())
    ) THEN
        RAISE EXCEPTION 'Only active students can join groups.';
    END IF;

    SELECT * INTO target_group FROM public.groups WHERE group_id = p_group_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Group not found.'; END IF;
    IF target_group.finalized_at IS NOT NULL THEN RAISE EXCEPTION 'This group is finalized.'; END IF;
    IF EXISTS (SELECT 1 FROM public.group_members WHERE user_id = p_user_id) THEN
        RAISE EXCEPTION 'You can only belong to one group.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.group_join_requests
        WHERE user_id = p_user_id AND status = 'Pending' AND expires_at > NOW()
    ) THEN
        RAISE EXCEPTION 'Your join request is still pending.';
    END IF;

    SELECT COUNT(*) INTO member_count FROM public.group_members WHERE group_id = p_group_id;
    IF member_count >= target_group.max_members OR target_group.status = 'Full' THEN
        UPDATE public.group_join_requests
        SET status = 'Expired'
        WHERE group_id = p_group_id AND status = 'Pending';
        RAISE EXCEPTION 'This group is full.';
    END IF;
    INSERT INTO public.group_join_requests (group_id, user_id) VALUES (p_group_id, p_user_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.approve_group_request(
    p_group_id BIGINT,
    p_request_id BIGINT,
    p_owner_id BIGINT
) RETURNS VOID
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    target_group public.groups;
    target_request public.group_join_requests;
    member_count INTEGER;
BEGIN
    SELECT * INTO target_group FROM public.groups WHERE group_id = p_group_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Group not found.'; END IF;
    IF target_group.owner_id <> p_owner_id THEN RAISE EXCEPTION 'Only the group owner can approve requests.'; END IF;
    IF target_group.finalized_at IS NOT NULL THEN RAISE EXCEPTION 'This group is finalized.'; END IF;

    UPDATE public.group_join_requests
    SET status = 'Expired'
    WHERE group_id = p_group_id AND status = 'Pending' AND expires_at <= NOW();
    SELECT * INTO target_request FROM public.group_join_requests
    WHERE request_id = p_request_id AND group_id = p_group_id
      AND status = 'Pending' AND expires_at > NOW()
    FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Join request not found or expired.'; END IF;

    SELECT COUNT(*) INTO member_count FROM public.group_members WHERE group_id = p_group_id;
    IF member_count >= target_group.max_members THEN
        UPDATE public.group_join_requests SET status = 'Expired'
        WHERE group_id = p_group_id AND status = 'Pending';
        UPDATE public.groups SET status = 'Full' WHERE group_id = p_group_id;
        RAISE EXCEPTION 'This group is full.';
    END IF;

    INSERT INTO public.group_members (group_id, user_id) VALUES (p_group_id, target_request.user_id);
    UPDATE public.group_join_requests SET status = 'Approved' WHERE request_id = p_request_id;
    UPDATE public.groups
    SET status = CASE WHEN member_count + 1 >= max_members THEN 'Full' ELSE 'Open' END
    WHERE group_id = p_group_id;
    IF member_count + 1 >= target_group.max_members THEN
        UPDATE public.group_join_requests SET status = 'Expired'
        WHERE group_id = p_group_id AND status = 'Pending';
    END IF;
END;
$$;

