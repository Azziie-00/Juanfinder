CREATE TABLE IF NOT EXISTS public.group_adviser_application_documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL UNIQUE
        REFERENCES public.group_adviser_applications(application_id) ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES public.groups(group_id) ON DELETE CASCADE,
    adviser_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    uploaded_by BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    file_name TEXT NOT NULL,
    storage_path TEXT NOT NULL UNIQUE,
    file_type TEXT NOT NULL CHECK (file_type IN (
        'application/pdf',
        'application/msword',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
    )),
    file_size BIGINT NOT NULL CHECK (file_size > 0 AND file_size <= 10485760),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS group_adviser_application_documents_adviser_idx
    ON public.group_adviser_application_documents(adviser_id, application_id);

ALTER TABLE public.group_adviser_application_documents ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.group_adviser_application_documents FROM anon, authenticated;
GRANT ALL ON public.group_adviser_application_documents TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.group_adviser_application_documents_document_id_seq TO service_role;

